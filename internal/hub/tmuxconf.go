package hub

import (
	"fmt"
	"path/filepath"
	"strconv"
	"strings"
)

// tmuxConfHeader starts the generated tmux.conf.
const tmuxConfHeader = "# generated by zenify hub — edits are overwritten\n"

// tmuxConf is the config of the hub tmux server (tmux >= 3.1): mouse, tabs
// on a top status line with the agent state icon, a clickable [+ agent],
// and prefix-less Alt keys (FR-12.2, FR-12.3). self is the zenify binary.
func tmuxConf(self string) string {
	newAgent := "run-shell -b " + tmuxDoubleQuote(ShellQuote(self)+" hub new-agent")
	lines := []string{
		"set -g mouse on",
		"set -g base-index 1",
		"setw -g pane-base-index 1",
		"set -g escape-time 10",
		"set -g focus-events on",
		"set -g set-clipboard on",
		"setw -gq allow-passthrough on", // tmux < 3.3 has no such option; -q ignores it
		"set -g status-position top",
		"set -g status-left ' zenify hub '",
		"set -g status-right ' [+ agent] '",
		"setw -g window-status-format ' #{?@hub_state,#{@hub_state} ,}#W '",
		"setw -g window-status-current-format '#[reverse] #{?@hub_state,#{@hub_state} ,}#W #[noreverse]'",
		"bind -n M-Left select-pane -L",
		"bind -n M-Right select-pane -R",
	}
	for i := 1; i <= 9; i++ {
		n := strconv.Itoa(i)
		lines = append(lines, "bind -n M-"+n+" select-window -t :="+n)
	}
	lines = append(lines,
		"bind -n M-n "+newAgent,
		"bind -n M-d detach-client",
		"bind -n MouseDown1Status select-window -t =",
		"bind -n MouseDown1StatusRight "+newAgent,
	)
	return tmuxConfHeader + strings.Join(lines, "\n") + "\n"
}

// ShellQuote single-quotes s for sh, escaping embedded single quotes.
func ShellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// tmuxDoubleQuote quotes s as one tmux config argument that run-shell passes
// to sh unchanged: \ " $ are escaped for the config parser, and # is doubled
// since run-shell expands formats.
func tmuxDoubleQuote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "#", "##")
	return `"` + r.Replace(s) + `"`
}

// WriteTmuxConf writes ~/.zenify/hub/tmux.conf (0600, atomically) for the
// zenify binary self and returns its path. Every launch rewrites it.
func WriteTmuxConf(home, self string) (string, error) {
	p := filepath.Join(Dir(home), "tmux.conf")
	if err := writeFileAtomic(Dir(home), p, ".tmux-*.tmp", []byte(tmuxConf(self))); err != nil {
		return "", fmt.Errorf("write tmux.conf: %w", err)
	}
	return p, nil
}
